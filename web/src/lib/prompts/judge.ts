export function buildJudgePrompt(userQuery: string, lawContext?: string): string {
  if (lawContext) {
    return `${JUDGE_SYSTEM_PROMPT}

## 相关法律参考

以下是检索到的相关法律条文，请在回答时参考：

${lawContext}

---
用户问题：${userQuery}`;
  }

  return `${JUDGE_SYSTEM_PROMPT}

---
用户问题：${userQuery}`;
}

